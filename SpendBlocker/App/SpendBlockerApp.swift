# 产品需求文档（PRD）

## 1. 产品名称
Spend Blocker

## 2. 产品定位
一款面向年轻人与职场人群的 iOS 预算管理与消费克制助手，核心价值是帮助用户在消费冲动阶段放慢脚步，减少无计划支出。

## 3. 用户痛点
- 钱花得快但不知道用在哪里
- 购物冲动时难以控制
- 每月预算缺乏实时提醒
- 流水账记账繁琐，统计不直观

## 4. 核心功能

### 4.1 预算管理
- 设置月度预算
- 设置分类预算
- 实时显示预算剩余情况
- 支出超出预算时出现预警

### 4.2 记账功能
- 记录金额、类别、日期、备注
- 支持快速记账
- 支持消费标签和分类

### 4.3 冷静期
- 当金额达到阈值时触发
- 停留 10 秒并提示“是否真的需要购买”
- 用户可以确认或取消

### 4.4 统计分析
- 分类支出比例
- 每周/月统计
- 近 30 天消费趋势

## 5. MVP 范围
- 一套预算管理基础页面
- 支出记账功能
- 预算提醒
- 冷静期提醒
- 统计展示

## 6. 非功能需求
- 数据本地保存
- 界面清晰、使用简单
- 支持 iOS 15+
- 数据逻辑稳定，低延迟

## 7. 交互流程
1. 用户进入首页，看到预算总览
2. 点击“记一笔”添加消费
3. 输入金额与分类
4. 若金额超过阈值，则进入冷静期
5. 冷静期结束后，再决定是否确认消费
6. 用户可以在统计页面查看趋势和分类支出

## 8. 未来迭代
- 自动同步银行卡/信用卡记录
- 预算自定义建议
- 存钱目标和提醒
- 语音输入记账
- AI 预算建议
